#!/usr/bin/env bash
# fa --scan: reconhece a máquina uma vez e grava ~/.config/fa/sistema.txt.
# Esse arquivo vai junto com o prompt: o modelo começa sabendo que sistema é este.
# Rodar de novo se a máquina mudar (distribuição, rede, ferramentas instaladas).
set -u
saida="${XDG_CONFIG_HOME:-$HOME/.config}/fa/sistema.txt"
mkdir -p "$(dirname "$saida")"
pt() { case "${LANGUAGE:-${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}}" in pt*) echo "$2" ;; *) echo "$1" ;; esac; }

# Cada comando aparece com a saída, do jeito que apareceria no terminal.
mostrar() {
    echo "\$ $*"
    timeout 5 bash -c "$*" 2>&1 | head -n 40
    echo
}

{
    echo "State of this machine, read by fa --scan on $(date '+%Y-%m-%d %H:%M'):"
    echo
    mostrar 'cat /etc/os-release'
    mostrar 'uname -srm'
    mostrar 'hostname'
    mostrar 'id'
    mostrar 'echo $SHELL'
    mostrar 'nproc; free -h'
    mostrar 'lsblk -o NAME,SIZE,TYPE,MOUNTPOINTS'
    mostrar 'df -h -x tmpfs -x devtmpfs -x efivarfs'
    mostrar 'ip -br addr'
    mostrar 'ip route'
    mostrar 'resolvectl dns 2>/dev/null || cat /etc/resolv.conf'
    mostrar 'nmcli -t -f NAME,TYPE,DEVICE connection show --active'
    mostrar 'systemctl list-units --type=service --state=running --no-legend --plain | cut -d" " -f1'
    mostrar 'for c in dnf apt pacman zypper flatpak snap firewall-cmd ufw iptables nft docker podman nmcli ss netstat ip ifconfig dig nslookup host traceroute tracepath nmap nc curl wget tcpdump python python3 node git; do command -v $c >/dev/null && printf "%s " $c; done; echo'
} > "$saida"

pt "fa: machine scan saved to $saida ($(wc -l < "$saida") lines)" "fa: reconhecimento gravado em $saida ($(wc -l < "$saida") linhas)"

# Exemplos de rede desta máquina (pack -n). Só cria se não existir: o arquivo é da pessoa, pra editar.
# Pra gerar de novo do zero: apagar o arquivo e rodar fa --scan. pacotes/redes.txt é o nome da 0.1.x.
local_redes="$(dirname "$saida")/packs/network.txt"
if [ ! -e "$local_redes" ] && [ ! -e "$(dirname "$saida")/pacotes/redes.txt" ]; then
    mkdir -p "$(dirname "$local_redes")"
    wifi=$(nmcli -t -f DEVICE,TYPE device 2>/dev/null | awk -F: '$2=="wifi"{print $1; exit}')
    cabo=$(nmcli -t -f DEVICE,TYPE device 2>/dev/null | awk -F: '$2=="ethernet"{print $1; exit}')
    instalar=$(for g in dnf apt zypper; do command -v $g >/dev/null && { echo "sudo $g install -y"; break; }; done)
    command -v pacman >/dev/null && instalar="sudo pacman -S --noconfirm"
    ativa=$(ip route show default 2>/dev/null | awk '{for(i=1;i<NF;i++) if($i=="dev"){print $(i+1); exit}}')
    {
        echo "# Network examples for THIS machine, generated by fa --scan on $(date '+%Y-%m-%d'). Edit freely."
        echo "# Format: request => command"
        [ -n "$ativa" ] && echo "active interface (the default route's at scan time) => $ativa"
        [ -n "$wifi" ] && echo "capture on wifi => sudo tcpdump -i $wifi -c 20 -nn"
        [ -n "$cabo" ] && echo "capture on ethernet => sudo tcpdump -i $cabo -c 20 -nn"
        [ -n "$wifi" ] && echo "my wifi ip => ip -br addr show $wifi"
        [ -n "$cabo" ] && echo "my ethernet ip => ip -br addr show $cabo"
        [ -n "$cabo" ] && echo "connect the ethernet cable => nmcli device connect $cabo"
        command -v tailscale >/dev/null && echo "tailscale status => tailscale status"
        command -v tailscale >/dev/null && echo "my tailscale ip => tailscale ip -4"
        command -v firewall-cmd >/dev/null && echo "show the firewall => sudo firewall-cmd --list-all"
        command -v firewall-cmd >/dev/null && echo "open a port in the firewall => sudo firewall-cmd --permanent --add-port=3000/tcp && sudo firewall-cmd --reload"
        command -v nmap >/dev/null || echo "find the live hosts on the network => $instalar nmap && sudo nmap -sn <network>/24"
        command -v mtr >/dev/null || echo "measure loss and latency along the path => tracepath host   (mtr not installed)"
    } > "$local_redes"
    pt "fa: network examples for this machine in $local_redes (edit freely)" "fa: exemplos de rede desta máquina em $local_redes (edite à vontade)"
fi
